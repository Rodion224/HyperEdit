function formatDict(name, dict) {
  let s = `export const ${name}: TranslationDictionary = {\n`;
  for (const [k, v] of Object.entries(dict)) {
    const escaped = v.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    s += `  '${k}': '${escaped}',\n`;
  }
  s += `};\n\n`;
  return s;
}

