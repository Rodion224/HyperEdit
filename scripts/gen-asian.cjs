function extractDict(name) {
  const start = asianTs.indexOf('export const ' + name);
  const nextStart = asianTs.indexOf('export const ', start + 20);
  const chunk = nextStart !== -1 ? asianTs.slice(start, nextStart) : asianTs.slice(start);
  const dict = {};
  for (const m of chunk.matchAll(/'([a-zA-Z0-9\._]+)':\s*'((?:[^'\\]|\\.)*)'/g)) {
    dict[m[1]] = m[2];
  }
  return dict;
}

